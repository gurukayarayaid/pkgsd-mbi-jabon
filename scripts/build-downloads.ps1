# Build the file list used by the Downloads page.
# Run from the project folder:
#   powershell -ExecutionPolicy Bypass -File scripts\build-downloads.ps1
# Keep this file ASCII-only so Windows PowerShell 5.1 can parse it.
$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot
$folders = @(
  'BG',
  'BS',
  'INFOGRAFIK-TOPIK-1',
  'LK',
  'LK-DONE',
  'RPP',
  'RPTM',
  'SPT',
  'STEP JIGSAW'
)

$groups = @()
foreach ($folder in $folders) {
  $dir = Join-Path $root $folder
  if (-not (Test-Path -LiteralPath $dir -PathType Container)) {
    Write-Warning "Folder not found: $folder - skipped."
    continue
  }

  $base = (Resolve-Path -LiteralPath $dir).Path
  $files = @()
  Get-ChildItem -LiteralPath $dir -Recurse -File | ForEach-Object {
    $name = $_.Name
    # Skip OS / Office temporary files.
    if ($name -eq '.DS_Store' -or $name.StartsWith('~$')) { return }

    $relative = $_.FullName.Substring($base.Length + 1).Replace('\', '/')
    $files += [pscustomobject]@{
      path = ($folder + '/' + $relative)
      rel  = $relative
      name = $name
      size = [long]$_.Length
    }
  }

  $groups += [pscustomobject]@{
    name  = $folder
    files = @($files)
  }
  Write-Output ("{0}: {1} berkas" -f $folder, $files.Count)
}

$manifest = [pscustomobject]@{
  generated = (Get-Date).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ')
  groups    = @($groups)
}
$json = $manifest | ConvertTo-Json -Depth 8 -Compress
$target = Join-Path $root 'assets/js/downloads-data.js'
$content = "/* Generated by scripts/build-downloads.ps1 - do not edit directly.`n   Re-run the script after adding/removing files in the material folders. */`nwindow.DOWNLOAD_MANIFEST = $json;`n"
[System.IO.File]::WriteAllText($target, $content, (New-Object System.Text.UTF8Encoding($false)))
Write-Output "Ditulis: $target"
